// Plant library. Mature sizes are typical landscape figures (they vary with
// cultivar, climate and pruning); zones are USDA hardiness ranges as commonly
// published. `native` lists the broad US regions where the species (not
// necessarily the cultivar) grows wild — a coarse flag, not a range map. An
// empty list means introduced, a hybrid, or not confidently placed; species we
// weren't sure of were left out rather than guessed.

export type PlantForm = 'tree' | 'shrub' | 'perennial' | 'grass' | 'groundcover';
export type Sun = 'full' | 'part' | 'shade';
export type Water = 'low' | 'medium' | 'high';
export type NativeRegion = 'northeast' | 'southeast' | 'midwest' | 'plains' | 'southwest' | 'mountain' | 'pacific';

